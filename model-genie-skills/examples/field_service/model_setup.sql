-- COMMAND ----------
-- =============================================================================
-- EMPTY TARGET SHELLS — NORMALIZED 3NF product tables the assessment inspects via
-- information_schema (Phase 1.4-1.6). Empty (0 rows), typed, natural-key PK / FK,
-- comments. Both flows read this STRUCTURE and CREATE their own copies in the LAND
-- catalog. technician exists as a shell but has no bronze source.
-- Created in FK-dependency order: customer, product, technician -> installed_asset -> service_order.
-- =============================================================================

CREATE TABLE customer (
  customer_id   STRING NOT NULL COMMENT 'PK — natural key (SAP kna1.kunnr)',
  customer_name STRING COMMENT 'Customer legal name',
  country_code  STRING COMMENT 'ISO-2 country',
  region        STRING COMMENT 'NA | EU | APAC',
  industry_code STRING COMMENT 'Industry key',
  CONSTRAINT pk_customer PRIMARY KEY (customer_id)
) COMMENT 'Customer master (SAP kna1). One row per customer account.';

CREATE TABLE product (
  product_id    STRING NOT NULL COMMENT 'PK — natural key (installed_asset.sku_code)',
  product_group STRING COMMENT 'valve | actuator | positioner | instrument',
  CONSTRAINT pk_product PRIMARY KEY (product_id)
) COMMENT 'Product/SKU master from FieldLink installed-asset attributes. One row per SKU.';

CREATE TABLE technician (
  technician_id   STRING NOT NULL COMMENT 'PK — NO clean bronze source',
  technician_name STRING COMMENT 'Free-text technician name (service_order.technician)',
  CONSTRAINT pk_technician PRIMARY KEY (technician_id)
) COMMENT 'Technician master — INTENTIONALLY unsourced. Bronze has only a free-text name on service_order; no employee master is landed. Expected gap.';

CREATE TABLE installed_asset (
  asset_id             STRING NOT NULL COMMENT 'PK — natural key (FieldLink asset_id)',
  serial_number        STRING COMMENT 'Unit serial number',
  customer_id          STRING COMMENT 'FK to customer',
  product_id           STRING COMMENT 'FK to product',
  commissioning_status STRING COMMENT 'commissioned | pending | failed',
  install_date         DATE   COMMENT 'Install date',
  warranty_end_date    DATE   COMMENT 'Warranty expiry',
  site_country         STRING COMMENT 'ISO-2 country of install site',
  CONSTRAINT pk_installed_asset PRIMARY KEY (asset_id),
  CONSTRAINT fk_asset_customer FOREIGN KEY (customer_id) REFERENCES customer(customer_id),
  CONSTRAINT fk_asset_product  FOREIGN KEY (product_id)  REFERENCES product(product_id)
) COMMENT 'Installed asset master (FieldLink installed_asset). One row per serialized unit.';

CREATE TABLE service_order (
  service_order_id STRING NOT NULL COMMENT 'PK — natural key (FieldLink service_order_id)',
  asset_id         STRING COMMENT 'FK to installed_asset',
  technician_id    STRING COMMENT 'FK to technician — UNRESOLVED (gap: bronze has only a free-text name)',
  order_type       STRING COMMENT 'preventive | corrective | inspection | calibration',
  opened_date      DATE   COMMENT 'Date opened',
  status           STRING COMMENT 'open | dispatched | completed | closed',
  priority         STRING COMMENT 'low | medium | high | critical',
  CONSTRAINT pk_service_order PRIMARY KEY (service_order_id),
  CONSTRAINT fk_so_asset FOREIGN KEY (asset_id)      REFERENCES installed_asset(asset_id),
  CONSTRAINT fk_so_tech  FOREIGN KEY (technician_id) REFERENCES technician(technician_id)
) COMMENT 'Service order (FieldLink service_order). One row per dispatched field-service job.';

