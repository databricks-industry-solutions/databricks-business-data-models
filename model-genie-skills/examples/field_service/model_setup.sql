-- SHAPE: the vibe model is a NORMALIZED, 3NF, single-source-of-truth SPEC — one
-- table per business entity, natural business keys as PKs (customer_id,
-- service_order_id, asset_id), snake_case product names, NO dim_/fact_ prefixes,
-- NO SHA2 surrogate keys. Both output_model flows build FROM this seed:
--   - dimensional flow  -> derives dim_/fact_ star + SHA2 surrogates (field_service_silver_dim)
--   - normalized flow   -> ports these tables 1:1 (field_service_silver_norm)
--
-- This is the READ-ONLY model location (conventions -> vibe_model.*). The ETL build
-- LANDS output into a SEPARATE catalog (catalogs.silver). Never point a build here.
--
-- Source bronze already exists: meridian_bronze.fieldlink + .sap_sd
-- (generated by examples/setup/data_generator). This script does NOT touch bronze.
--
-- Run once. Idempotent: CREATE OR REPLACE on metamodel tables; shells dropped +
-- recreated. Catalog/schema are runtime params (widgets), never hard-coded.
-- =============================================================================

